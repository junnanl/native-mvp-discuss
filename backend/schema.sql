CREATE TABLE IF NOT EXISTS "user" (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  role TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS form_def (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  fields JSON NOT NULL
);

CREATE TABLE IF NOT EXISTS flow_def (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  nodes JSON NOT NULL
);

CREATE TABLE IF NOT EXISTS flow_instance (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  flow_def_id INTEGER NOT NULL REFERENCES flow_def(id),
  current_node TEXT NOT NULL,
  status TEXT NOT NULL,
  creator_id INTEGER NOT NULL REFERENCES "user"(id),
  data JSON NOT NULL,
  visible_to JSON NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  finished_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS agent (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  description TEXT NOT NULL,
  avatar TEXT,
  category TEXT NOT NULL,
  maturity TEXT,
  tags JSON NOT NULL,
  quick_questions JSON NOT NULL,
  capabilities JSON NOT NULL,
  skill_md TEXT,
  harness_url TEXT,
  harness_key TEXT,
  status TEXT NOT NULL,
  usage_count INTEGER NOT NULL DEFAULT 0,
  flow_instance_id INTEGER REFERENCES flow_instance(id),
  visible_to JSON NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS prompt_suggestion (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  page_key TEXT NOT NULL,
  text TEXT NOT NULL,
  "order" INTEGER NOT NULL
);
